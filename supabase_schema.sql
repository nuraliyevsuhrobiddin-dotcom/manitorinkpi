-- ─── 9. AUTH.USERS TRIGGER (avtomatik app_users yaratish) ────
-- Superadmin yangi foydalanuvchi yaratganda auth.users ga qo'shiladi.
-- Bu trigger app_users jadvaliga ham avtomatik yozadi.

create or replace function public.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.app_users (id, email, full_name, role, department_id, faculty_id)
  values (
    new.id,
    new.email,
    coalesce(
      new.raw_user_meta_data ->> 'full_name',
      new.raw_user_meta_data ->> 'fullName',
      ''
    ),
    coalesce(
      lower(new.raw_user_meta_data ->> 'role'),
      'guest'
    ),
    nullif((new.raw_user_meta_data ->> 'departmentId')::text, '')::bigint,
    nullif((new.raw_user_meta_data ->> 'facultyId')::text, '')::bigint
  )
  on conflict (id) do update set
    email         = excluded.email,
    full_name     = excluded.full_name,
    role          = excluded.role,
    department_id = excluded.department_id,
    faculty_id    = excluded.faculty_id,
    updated_at    = now();
  return new;
end;
$$;

-- Trigger: yangi auth user paydo bo'lganda chaqiriladi
drop trigger if exists on_auth_user_created on auth.users;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_auth_user();

-- ─── 10. TASDIQLASH ──────────────────────────────────────────
-- Pastdagi so'rov barcha jadvallarni va ularning ustunlarini ko'rsatadi.
-- Supabase SQL Editor → Run → natijani tekshiring.

select
  t.table_name,
  string_agg(c.column_name || ' ' || c.data_type, ', ' order by c.ordinal_position) as columns
from information_schema.tables t
join information_schema.columns c
  on c.table_schema = t.table_schema and c.table_name = t.table_name
where t.table_schema = 'public'
  and t.table_type = 'BASE TABLE'
group by t.table_name
order by t.table_name;
