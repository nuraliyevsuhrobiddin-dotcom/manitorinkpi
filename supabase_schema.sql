-- ─── 6. is_app_admin() FUNKSIYASI ────────────────────────────
-- Tekshirish tartibi:
--   1. app_metadata.role  → faqat service-role key yoza oladi (xavfsiz)
--   2. Email whitelist    → jadval lookup kerak emas (ishonchli)
--   3. app_users jadvalidagi rol (SECURITY DEFINER — RLS chetlab o'tadi)
--
-- XAVFSIZLIK: user_metadata.role TEKSHIRILMAYDI.
-- user_metadata ni har qanday foydalanuvchi signup paytida
-- o'zi yoza oladi (anon key orqali) — shuning uchun u ishonchsiz.

create or replace function public.is_app_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce(
    -- 1. app_metadata.role (xavfsiz — faqat server tomonidan yoziladi)
    lower(coalesce(auth.jwt() -> 'app_metadata' ->> 'role', ''))
      = any (array['admin', 'superadmin', 'dekan', 'kafedra_mudiri',
                   'ilmiy_bolim', 'buxgalter', 'kadrlar'])

    -- 2. Email whitelist (JWT dan — jadval lookup kerak emas)
    or lower(coalesce(auth.jwt() ->> 'email', ''))
      = any (array['suhrobiddinnuraliyev04@gmail.com'])

    -- 3. app_users jadvalidagi rol (SECURITY DEFINER — RLS yo'q)
    or exists (
      select 1
      from   public.app_users
      where  id   = auth.uid()
        and  role in ('admin', 'superadmin', 'dekan', 'kafedra_mudiri',
                      'ilmiy_bolim', 'buxgalter', 'kadrlar')
    ),
    false
  );
$$;

